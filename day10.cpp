#include <iostream>
using namespace std;

// ============================================================
// 1. 求二维数组第 col 列的最小值
//    参数：a   —— 二维数组（列数固定为 4）
//          col —— 列号，0 ~ 3
//    返回：这一列的最小值
// ============================================================
int columnMin(int a[][4], int col) {
    int m = a[0][col];                 // 先让第 0 行当"擂主"

    for (int i = 1; i < 4; i++) {      // 从第 1 行开始挑战
        if (a[i][col] < m) {
            m = a[i][col];             // 更小就换擂主
        }
    }
    return m;
}

// ============================================================
// 2. 求 a 和 b 的最大公约数（辗转相除法）
//    参数：a, b —— 正整数
//    返回：最大公约数
// ============================================================
int gcd(int a, int b) {
    while (b != 0) {
        int t = a % b;                 // 余数
        a = b;                         // b 上位
        b = t;                         // 余数变成新的 b
    }
    return a;                          // b 为 0 时，a 就是答案
}

// ============================================================
// 3. 求 base 的 exp 次方（整数连乘）
//    参数：base —— 底数
//          exp  —— 指数（>= 0）
//    返回：base^exp
// ============================================================
long long power(long long base, int exp) {
    long long result = 1;              // 乘法单位元，必须是 1

    for (int i = 0; i < exp; i++) {
        result *= base;                // 乘 exp 次
    }
    return result;
}

// ============================================================
// 测试
// ============================================================
int main() {
    int a[4][4] = {
        { 3,  6,  0, 8},
        { 5, 12,  7, 9},
        {11, 90, 61, 1},
        {23, -5,  2, 66}
    };

    for (int j = 0; j < 4; j++) {
        cout << columnMin(a, j) << " ";
    }
    cout << endl;                      // 3 -5 0 1

    cout << gcd(12, 18) << endl;       // 6
    cout << gcd(100, 75) << endl;      // 25

    cout << power(2, 10) << endl;      // 1024
    cout << power(3, 5) << endl;       // 243

    return 0;
}
